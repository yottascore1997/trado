"""
setup_tracker_engine.py
======================
Institutional All-Opportunity Setup Execution & Trailing SL Tracker.
Tracks every valid A+ and A tier setup generated by the screener across the entire market,
free from the 2-trade capital bottleneck of the real/paper wallet.

Specification:
- Allocation per trade: ₹50,000 Base Capital
- Leverage: 2x (Total Exposure per trade: ₹1,00,000 / ₹1 Lakh)
- Filters: strictly A+ Institutional and A High-Probability setups
- Full Dynamic Trailing SL Lifecycle:
    Stage 1: Breakeven (+ Charges friction) at 35% target move
    Stage 2: Profit Lock 25% at 50% target move
    Stage 3: Profit Lock 50% at 75% target move
    Stage 4: Super Profit Lock 70% at 90% target move
- Real-time MTM P&L (₹ & % on ₹50k capital)
- Automated Target Hit (🎯), Trailing SL Hit (🔒), Stop Loss Hit (🛑), and 15:15 IST Square-off
- Real persistent state (survives app reloads & refreshes)
"""

import json
import logging
import threading
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional
from zoneinfo import ZoneInfo

logger = logging.getLogger("SetupTrackerEngine")
IST = ZoneInfo("Asia/Kolkata")
DATA_DIR = Path(__file__).resolve().parent.parent.parent / "data"
STATE_FILE = DATA_DIR / "setup_tracker_state.json"


class SetupTrackerEngine:
    def __init__(self, persist: bool = True):
        self._lock = threading.RLock()
        self.persist = persist
        self.base_capital: float = 50000.0
        self.leverage: float = 2.0
        self.exposure_per_trade: float = 100000.0

        self.active_setups: List[Dict[str, Any]] = []
        self.closed_setups: List[Dict[str, Any]] = []
        self.last_feed_time: Optional[datetime] = None

        if self.persist:
            self._load_persisted_state()

    def _load_persisted_state(self):
        """Loads persistent setup tracker trades."""
        try:
            DATA_DIR.mkdir(parents=True, exist_ok=True)
            if STATE_FILE.exists():
                with open(STATE_FILE, "r", encoding="utf-8") as f:
                    saved = json.load(f)
                    if isinstance(saved, dict):
                        self.active_setups = saved.get("active_setups", [])
                        self.closed_setups = saved.get("closed_setups", [])
                        logger.info(
                            f"Loaded persistent setup tracker state: {len(self.active_setups)} active, "
                            f"{len(self.closed_setups)} closed setups."
                        )
        except Exception as e:
            logger.warning(f"Could not load setup tracker state: {e}")

    def _save_persisted_state(self):
        """Saves setup tracker state to JSON file."""
        if not getattr(self, "persist", True):
            return
        try:
            DATA_DIR.mkdir(parents=True, exist_ok=True)
            state = {
                "base_capital": self.base_capital,
                "leverage": self.leverage,
                "exposure_per_trade": self.exposure_per_trade,
                "active_setups": self.active_setups,
                "closed_setups": self.closed_setups,
                "last_updated": datetime.now(timezone.utc).isoformat(),
            }
            with open(STATE_FILE, "w", encoding="utf-8") as f:
                json.dump(state, f, indent=2, default=str)
        except Exception as e:
            logger.warning(f"Could not save setup tracker state: {e}")

    def calculate_position_sizing(self, price: float) -> tuple[int, float, float]:
        """
        Calculates quantity and margin deployed using ₹50k base margin with 2x leverage (₹100k exposure).
        Returns: (quantity, margin_deployed, total_exposure)
        """
        safe_price = max(price, 0.05)
        qty = max(1, int(self.exposure_per_trade / safe_price))
        total_exposure = round(qty * safe_price, 2)
        margin_deployed = round(total_exposure / self.leverage, 2)
        return qty, margin_deployed, total_exposure

    def process_market_tick(
        self,
        live_quotes: Dict[str, Any],
        top_setups: Optional[List[Dict[str, Any]]] = None,
        current_time: Optional[datetime] = None,
    ):
        """
        Processes market tick:
        1. Updates live LTP and trailing SL for all active setups.
        2. Evaluates exit triggers (Target, Trailing SL, Square-off).
        3. Enters fresh A+/A setups with ₹50k base margin & 2x leverage.
        """
        now_ist = current_time if current_time is not None else datetime.now(IST)
        is_square_off_time = (now_ist.hour > 15) or (now_ist.hour == 15 and now_ist.minute >= 15)

        setups_to_close = []

        with self._lock:
            self.last_feed_time = now_ist

            # -------------------------------------------------------------
            # STEP 1: Update Existing Active Setups & Dynamic Trailing SL
            # -------------------------------------------------------------
            for pos in self.active_setups:
                sym = pos["symbol"]
                quote = live_quotes.get(f"NSE_EQ:{sym}") or live_quotes.get(f"NSE_EQ|{sym}")

                # Dynamic Option Quote Resolution if applicable
                if not quote and ("BANKNIFTY" in sym or "NIFTY" in sym):
                    is_bn = "BANKNIFTY" in sym
                    idx_key = "NSE_INDEX:Nifty Bank" if is_bn else "NSE_INDEX:Nifty 50"
                    idx_quote = live_quotes.get(idx_key) or live_quotes.get(idx_key.replace(":", "|"))
                    if idx_quote and "last_price" in idx_quote:
                        curr_spot = float(idx_quote["last_price"])
                        if "entry_index_spot" not in pos:
                            pos["entry_index_spot"] = curr_spot
                        spot_diff = curr_spot - pos["entry_index_spot"]
                        opt_pts = (spot_diff * 0.50) if "CE" in sym else (-spot_diff * 0.50)
                        sim_opt_ltp = max(1.0, round(pos["entry_price"] + opt_pts, 2))
                        quote = {
                            "last_price": sim_opt_ltp,
                            "average_price": sim_opt_ltp,
                            "ohlc": {"open": sim_opt_ltp, "high": sim_opt_ltp, "low": sim_opt_ltp, "close": sim_opt_ltp},
                        }

                if quote and "last_price" in quote:
                    current_price = float(quote["last_price"])
                    pos["current_price"] = current_price
                    pos["last_updated"] = datetime.now(timezone.utc).isoformat()

                    # Live VWAP calculation from exchange quote
                    ohlc = quote.get("ohlc", {})
                    open_p = float(ohlc.get("open", current_price))
                    high_p = float(ohlc.get("high", current_price))
                    low_p = float(ohlc.get("low", current_price))
                    curr_vwap = float(quote.get("average_price") or quote.get("vwap") or round((open_p + high_p + low_p + current_price) / 4.0, 2))

                    side = pos["side"]
                    entry = pos["entry_price"]
                    qty = pos["quantity"]
                    target = pos["target_price"]
                    margin = pos["margin_required"]

                    # Accurate regulatory friction per share (~₹85 round-trip charges covered)
                    per_share_friction = round((85.0 / max(qty, 1)) + 0.05, 2)

                    if side == "BUY":
                        pnl = round((current_price - entry) * qty, 2)
                        pnl_pct = round((pnl / max(margin, 1.0)) * 100.0, 2)
                        pos["unrealized_pnl"] = pnl
                        pos["pnl_pct"] = pnl_pct

                        if current_price > pos.get("highest_price", entry):
                            pos["highest_price"] = current_price

                        target_dist = target - entry
                        if target_dist > 0:
                            gain_ratio = (current_price - entry) / target_dist

                            # Stage 4: Super Profit Lock (90%+ near target) -> Lock 70% of target move
                            if gain_ratio >= 0.90:
                                lock_px = round(entry + (target_dist * 0.70), 2)
                                if lock_px > pos["stop_loss"]:
                                    pos["stop_loss"] = lock_px
                                    pos["trailing_stage"] = "PROFIT_LOCK_70"
                                    pos["trailing_description"] = f"Super Lock: 70% Target Secured (₹{lock_px})"
                            # Stage 3: Profit Lock (75%+ of target distance) -> Lock 50% of target move
                            elif gain_ratio >= 0.75:
                                lock_px = round(entry + (target_dist * 0.50), 2)
                                if lock_px > pos["stop_loss"]:
                                    pos["stop_loss"] = lock_px
                                    pos["trailing_stage"] = "PROFIT_LOCK_50"
                                    pos["trailing_description"] = f"Profit Lock: 50% Target Secured (₹{lock_px})"
                            # Stage 2: Profit Lock (50%+ of target distance) -> Lock 25% of target move
                            elif gain_ratio >= 0.50:
                                lock_px = round(entry + (target_dist * 0.25), 2)
                                if lock_px > pos["stop_loss"]:
                                    pos["stop_loss"] = lock_px
                                    pos["trailing_stage"] = "PROFIT_LOCK_25"
                                    pos["trailing_description"] = f"Profit Lock: 25% Target Secured (₹{lock_px})"
                            # Stage 1: True Breakeven (35%+ of target distance) -> Shift SL to Entry + Full Charges Friction
                            elif gain_ratio >= 0.35:
                                be_sl = round(entry + per_share_friction, 2)
                                if pos["stop_loss"] < be_sl:
                                    pos["stop_loss"] = be_sl
                                    pos["trailing_stage"] = "BREAKEVEN"
                                    pos["trailing_description"] = f"Breakeven Protected: Entry + Charges (₹{be_sl})"

                        # Dynamic In-Trade Defensive Exits
                        # A. Thesis Invalidation (Price sustained below VWAP for 3 ticks)
                        if curr_vwap > 0 and current_price < (curr_vwap - max(0.15, curr_vwap * 0.002)):
                            if (entry - current_price) >= max(0.20, entry * 0.0025):
                                b_count = pos.get("vwap_breach_count", 0) + 1
                                pos["vwap_breach_count"] = b_count
                                if b_count >= 3:
                                    logger.info(f"⚡ [THESIS INVALIDATED] {sym}: Price sustained below VWAP. Early exit.")
                                    setups_to_close.append((pos["setup_id"], "THESIS_INVALIDATED", current_price))
                        else:
                            pos["vwap_breach_count"] = 0

                        # B. Stagnation Time-Stop (Open > 35m and underwater by >= 0.30%)
                        entry_t_str = pos.get("entry_time")
                        if entry_t_str and pos["setup_id"] not in [s[0] for s in setups_to_close]:
                            try:
                                edt = datetime.fromisoformat(entry_t_str)
                                if edt.tzinfo is None:
                                    edt = edt.replace(tzinfo=IST)
                                elapsed_mins = (now_ist - edt).total_seconds() / 60.0
                                if elapsed_mins >= 35.0 and pos.get("unrealized_pnl", 0.0) < 0:
                                    if abs(pos.get("pnl_pct", 0.0)) >= 0.30:
                                        logger.info(f"⏱️ [STAGNATION EXIT] {sym}: Stalled after {elapsed_mins:.0f}m.")
                                        setups_to_close.append((pos["setup_id"], "STAGNATION_EXIT", current_price))
                            except Exception:
                                pass

                        # Standard Exit checks
                        if is_square_off_time:
                            setups_to_close.append((pos["setup_id"], "INTRADAY_SQUARE_OFF", current_price))
                        elif current_price >= target:
                            setups_to_close.append((pos["setup_id"], "TARGET_HIT", current_price))
                        elif current_price <= pos["stop_loss"]:
                            stage = pos.get("trailing_stage", "INITIAL")
                            reason = (
                                "TRAILING_SL_HIT"
                                if "PROFIT_LOCK" in stage
                                else ("BREAKEVEN_EXIT" if stage == "BREAKEVEN" else "STOP_LOSS_HIT")
                            )
                            setups_to_close.append((pos["setup_id"], reason, current_price))

                    elif side == "SELL":
                        pnl = round((entry - current_price) * qty, 2)
                        pnl_pct = round((pnl / max(margin, 1.0)) * 100.0, 2)
                        pos["unrealized_pnl"] = pnl
                        pos["pnl_pct"] = pnl_pct

                        if current_price < pos.get("lowest_price", entry):
                            pos["lowest_price"] = current_price

                        target_dist = entry - target
                        if target_dist > 0:
                            gain_ratio = (entry - current_price) / target_dist

                            # Stage 4: Super Profit Lock (90%+ near target) -> Lock 70% of target move
                            if gain_ratio >= 0.90:
                                lock_px = round(entry - (target_dist * 0.70), 2)
                                if lock_px < pos["stop_loss"]:
                                    pos["stop_loss"] = lock_px
                                    pos["trailing_stage"] = "PROFIT_LOCK_70"
                                    pos["trailing_description"] = f"Super Lock: 70% Target Secured (₹{lock_px})"
                            # Stage 3: Profit Lock (75%+ of target distance) -> Lock 50% of target move
                            elif gain_ratio >= 0.75:
                                lock_px = round(entry - (target_dist * 0.50), 2)
                                if lock_px < pos["stop_loss"]:
                                    pos["stop_loss"] = lock_px
                                    pos["trailing_stage"] = "PROFIT_LOCK_50"
                                    pos["trailing_description"] = f"Profit Lock: 50% Target Secured (₹{lock_px})"
                            # Stage 2: Profit Lock (50%+ of target distance) -> Lock 25% of target move
                            elif gain_ratio >= 0.50:
                                lock_px = round(entry - (target_dist * 0.25), 2)
                                if lock_px < pos["stop_loss"]:
                                    pos["stop_loss"] = lock_px
                                    pos["trailing_stage"] = "PROFIT_LOCK_25"
                                    pos["trailing_description"] = f"Profit Lock: 25% Target Secured (₹{lock_px})"
                            # Stage 1: True Breakeven (35%+ of target distance) -> Shift SL to Entry - Full Charges Friction
                            elif gain_ratio >= 0.35:
                                be_sl = round(entry - per_share_friction, 2)
                                if pos["stop_loss"] > be_sl:
                                    pos["stop_loss"] = be_sl
                                    pos["trailing_stage"] = "BREAKEVEN"
                                    pos["trailing_description"] = f"Breakeven Protected: Entry - Charges (₹{be_sl})"

                        # Dynamic In-Trade Defensive Exits for SELL
                        # A. Thesis Invalidation
                        if curr_vwap > 0 and current_price > (curr_vwap + max(0.15, curr_vwap * 0.002)):
                            if (current_price - entry) >= max(0.20, entry * 0.0025):
                                b_count = pos.get("vwap_breach_count", 0) + 1
                                pos["vwap_breach_count"] = b_count
                                if b_count >= 3:
                                    logger.info(f"⚡ [THESIS INVALIDATED] {sym}: Price sustained above VWAP. Early exit.")
                                    setups_to_close.append((pos["setup_id"], "THESIS_INVALIDATED", current_price))
                        else:
                            pos["vwap_breach_count"] = 0

                        # B. Stagnation Time-Stop
                        entry_t_str = pos.get("entry_time")
                        if entry_t_str and pos["setup_id"] not in [s[0] for s in setups_to_close]:
                            try:
                                edt = datetime.fromisoformat(entry_t_str)
                                if edt.tzinfo is None:
                                    edt = edt.replace(tzinfo=IST)
                                elapsed_mins = (now_ist - edt).total_seconds() / 60.0
                                if elapsed_mins >= 35.0 and pos.get("unrealized_pnl", 0.0) < 0:
                                    if abs(pos.get("pnl_pct", 0.0)) >= 0.30:
                                        logger.info(f"⏱️ [STAGNATION EXIT] {sym}: Stalled after {elapsed_mins:.0f}m.")
                                        setups_to_close.append((pos["setup_id"], "STAGNATION_EXIT", current_price))
                            except Exception:
                                pass

                        # Standard Exit checks
                        if is_square_off_time:
                            setups_to_close.append((pos["setup_id"], "INTRADAY_SQUARE_OFF", current_price))
                        elif current_price <= target:
                            setups_to_close.append((pos["setup_id"], "TARGET_HIT", current_price))
                        elif current_price >= pos["stop_loss"]:
                            stage = pos.get("trailing_stage", "INITIAL")
                            reason = (
                                "TRAILING_SL_HIT"
                                if "PROFIT_LOCK" in stage
                                else ("BREAKEVEN_EXIT" if stage == "BREAKEVEN" else "STOP_LOSS_HIT")
                            )
                            setups_to_close.append((pos["setup_id"], reason, current_price))

            # Macro NIFTY 50 Crack & Reversal Guard
            nifty_quote = live_quotes.get("NSE_INDEX:Nifty 50") or live_quotes.get("NSE_INDEX|Nifty 50")
            if nifty_quote and "last_price" in nifty_quote:
                n_ltp = float(nifty_quote["last_price"])
                n_ohlc = nifty_quote.get("ohlc", {})
                n_open = float(n_ohlc.get("open", n_ltp))
                n_high = float(n_ohlc.get("high", n_ltp))
                n_low = float(n_ohlc.get("low", n_ltp))
                n_vwap = round((n_open + n_high + n_low + n_ltp) / 4.0, 1) if n_open > 0 else n_ltp

                # If NIFTY cracks > 0.20% below intraday VWAP, market is under sharp institutional liquidation
                if n_vwap > 0 and n_ltp < (n_vwap * 0.9980):
                    for pos in self.active_setups:
                        if pos["side"] == "BUY" and pos["setup_id"] not in [s[0] for s in setups_to_close]:
                            if pos.get("unrealized_pnl", 0.0) < 0:
                                logger.info(f"📉 [NIFTY CRACK EXIT] {pos['symbol']}: Nifty 50 cracked below VWAP. Defensive cut.")
                                setups_to_close.append((pos["setup_id"], "MARKET_REVERSAL_CRACK", pos["current_price"]))
                            else:
                                per_sh_f = round((85.0 / max(pos["quantity"], 1)) + 0.05, 2)
                                be_sl = round(pos["entry_price"] + per_sh_f, 2)
                                if pos["stop_loss"] < be_sl:
                                    pos["stop_loss"] = be_sl
                                    pos["trailing_stage"] = "BREAKEVEN"
                                    pos["trailing_description"] = f"NIFTY Crack: Protected at Cost (₹{be_sl})"

            # Execute pending closures
            for setup_id, reason, exit_price in setups_to_close:
                self._execute_close(setup_id, reason, exit_price, current_time=now_ist)

            # -------------------------------------------------------------
            # STEP 2: Auto-Enter New A+ and A Setups (Unlimited Capacity)
            # -------------------------------------------------------------
            if top_setups and not is_square_off_time:
                for setup in top_setups:
                    sym = setup.get("symbol")
                    if not sym:
                        continue

                    # Filter: Only A+ and A setups
                    tier = setup.get("setup_tier", "B")
                    signal = setup.get("signal")
                    if tier not in ("A+", "A") or signal not in ("BUY", "SELL"):
                        continue

                    # Strict Anti-Chasing Filter: Never enter over-extended setups (>1.6% from open or >0.85% from VWAP)
                    if setup.get("is_extended", False) or setup.get("entry_status") == "EXTENDED_MISSED":
                        logger.debug(f"Skipping extended setup for {sym}: Price already over-extended.")
                        continue

                    # Avoid duplicate active positions for the same symbol
                    if any(p["symbol"] == sym for p in self.active_setups):
                        continue

                    price = float(setup.get("price") or setup.get("entry_price", 0.0))
                    if price <= 0:
                        continue

                    sl = float(setup.get("stop_loss", price * 0.985 if signal == "BUY" else price * 1.015))
                    target = float(setup.get("target_price", price * 1.03 if signal == "BUY" else price * 0.97))

                    # 2x Leverage calculation on ₹50k capital
                    qty, margin_req, total_exposure = self.calculate_position_sizing(price)

                    setup_entry = {
                        "setup_id": f"SET-{uuid.uuid4().hex[:8].upper()}",
                        "symbol": sym,
                        "setup_tier": tier,  # "A+" or "A"
                        "tier_label": "⭐ A+ Institutional" if tier == "A+" else "✨ A High Conviction",
                        "setup_type": setup.get("setup_type") or setup.get("pattern") or "Algorithmic Setup",
                        "side": signal,
                        "quantity": qty,
                        "entry_price": round(price, 2),
                        "current_price": round(price, 2),
                        "initial_stop_loss": round(sl, 2),
                        "stop_loss": round(sl, 2),
                        "target_price": round(target, 2),
                        "highest_price": round(price, 2),
                        "lowest_price": round(price, 2),
                        "trailing_stage": "INITIAL",
                        "trailing_description": f"Initial Stop Loss at ₹{round(sl, 2)}",
                        "base_capital": self.base_capital,
                        "leverage": self.leverage,
                        "margin_required": margin_req,
                        "total_exposure": total_exposure,
                        "unrealized_pnl": 0.0,
                        "pnl_pct": 0.0,
                        "product_type": "MIS (2x)",
                        "entry_time": now_ist.isoformat(),
                        "last_updated": now_ist.isoformat(),
                        "rvol": float(setup.get("rvol", 1.5)),
                        "score": float(setup.get("score") or setup.get("ai_score") or 85.0),
                    }

                    self.active_setups.append(setup_entry)
                    logger.info(
                        f"⚡ [SETUP TRACKER] Entered {tier} {signal} on {sym} @ ₹{price:.2f} | "
                        f"Qty: {qty} (Exp: ₹{total_exposure:,.0f}, Margin: ₹{margin_req:,.0f}) | SL: ₹{sl:.2f} -> Tgt: ₹{target:.2f}"
                    )

            self._save_persisted_state()

    def _execute_close(
        self,
        setup_id: str,
        reason: str,
        exit_price: float,
        current_time: Optional[datetime] = None,
    ) -> Optional[Dict[str, Any]]:
        """Executes exit for a setup trade and computes realistic charges & net PnL."""
        now = current_time if current_time is not None else datetime.now(IST)

        pos = None
        for i, p in enumerate(self.active_setups):
            if p["setup_id"] == setup_id:
                pos = self.active_setups.pop(i)
                break

        if not pos:
            return None

        entry = pos["entry_price"]
        exit_px = float(exit_price)
        qty = pos["quantity"]
        side = pos["side"]
        margin = pos["margin_required"]

        if side == "BUY":
            gross = round((exit_px - entry) * qty, 2)
        else:
            gross = round((entry - exit_px) * qty, 2)

        # Realistic Institutional Brokerage & Regulatory Charges for 2x MIS
        turnover = round((entry + exit_px) * qty, 2)
        brokerage = min(40.0, round(turnover * 0.0005, 2))
        stt = round((exit_px * qty if side == "BUY" else entry * qty) * 0.00025, 2)
        exch_fee = round(turnover * 0.0000297, 2)
        gst = round((brokerage + exch_fee) * 0.18, 2)
        sebi_fee = round(max(0.01, turnover * 0.000001), 2)
        stamp_duty = round((entry * qty if side == "BUY" else exit_px * qty) * 0.00003, 2)

        charges = max(5.0, round(brokerage + stt + exch_fee + gst + sebi_fee + stamp_duty, 2))
        net = round(gross - charges, 2)
        net_roi_pct = round((net / max(margin, 1.0)) * 100.0, 2)

        closed_item = {
            "setup_id": pos["setup_id"],
            "symbol": pos["symbol"],
            "setup_tier": pos["setup_tier"],
            "tier_label": pos.get("tier_label", "A High Conviction"),
            "setup_type": pos.get("setup_type", "Algorithmic Setup"),
            "side": side,
            "quantity": qty,
            "entry_price": entry,
            "exit_price": round(exit_px, 2),
            "entry_time": pos["entry_time"],
            "exit_time": now.isoformat(),
            "date": now.strftime("%Y-%m-%d"),
            "margin_required": margin,
            "total_exposure": pos.get("total_exposure", round(qty * entry, 2)),
            "gross_pnl": gross,
            "charges": charges,
            "net_pnl": net,
            "roi_pct": net_roi_pct,
            "exit_reason": reason,
            "trailing_stage": pos.get("trailing_stage", "INITIAL"),
            "trailing_description": pos.get("trailing_description", ""),
            "stop_loss": pos["stop_loss"],
            "target_price": pos["target_price"],
            "highest_price": pos.get("highest_price", entry),
            "lowest_price": pos.get("lowest_price", entry),
        }

        # Keep latest closed setups at front
        self.closed_setups.insert(0, closed_item)
        if len(self.closed_setups) > 200:
            self.closed_setups = self.closed_setups[:200]

        logger.info(
            f"🎯 [SETUP TRACKER CLOSED] {pos['symbol']} ({pos['setup_tier']}): Exit @ ₹{exit_px:.2f} | "
            f"Reason: {reason} | Net PnL: ₹{net:+.2f} ({net_roi_pct:+.2f}%)"
        )
        return closed_item

    def manual_close(self, setup_id: str) -> Optional[Dict[str, Any]]:
        """Allows manual closure from the dashboard."""
        with self._lock:
            for pos in self.active_setups:
                if pos["setup_id"] == setup_id:
                    exit_px = pos.get("current_price", pos["entry_price"])
                    closed = self._execute_close(setup_id, "MANUAL_CLOSE", exit_px)
                    self._save_persisted_state()
                    return closed
        return None

    def reset_tracker(self):
        """Clears all active and closed setup records."""
        with self._lock:
            self.active_setups.clear()
            self.closed_setups.clear()
            self._save_persisted_state()

    def get_summary(self, current_time: Optional[datetime] = None) -> Dict[str, Any]:
        """
        Returns full real-time telemetry of the setup tracker:
        - Active setups with live PnL and trailing SL
        - Closed setups for today
        - Key aggregate metrics (Win Rate, Total PnL, A+ vs A counts)
        """
        now = current_time if current_time is not None else datetime.now(IST)
        today_str = now.strftime("%Y-%m-%d")

        with self._lock:
            today_closed = [c for c in self.closed_setups if c.get("date") == today_str]

            a_plus_active = sum(1 for p in self.active_setups if p.get("setup_tier") == "A+")
            a_active = sum(1 for p in self.active_setups if p.get("setup_tier") == "A")

            a_plus_closed = sum(1 for c in today_closed if c.get("setup_tier") == "A+")
            a_closed = sum(1 for c in today_closed if c.get("setup_tier") == "A")

            total_a_plus = a_plus_active + a_plus_closed
            total_a = a_active + a_closed
            total_setups_today = len(self.active_setups) + len(today_closed)

            wins = sum(1 for c in today_closed if c.get("net_pnl", 0.0) > 0)
            losses = sum(1 for c in today_closed if c.get("net_pnl", 0.0) < 0)
            breakevens = sum(1 for c in today_closed if c.get("net_pnl", 0.0) == 0)

            win_rate = round((wins / max(len(today_closed), 1)) * 100.0, 1) if today_closed else 0.0

            unrealized_mtm = round(sum(p.get("unrealized_pnl", 0.0) for p in self.active_setups), 2)
            realized_gross = round(sum(c.get("gross_pnl", 0.0) for c in today_closed), 2)
            realized_charges = round(sum(c.get("charges", 0.0) for c in today_closed), 2)
            realized_net = round(sum(c.get("net_pnl", 0.0) for c in today_closed), 2)
            total_combined_pnl = round(unrealized_mtm + realized_net, 2)

            total_margin_deployed = round(sum(p.get("margin_required", 0.0) for p in self.active_setups), 2)

            # Retrieve Top 4 Sniper Focus Picks from Screener Service
            top_sniper_picks = []
            sector_perf = {}
            try:
                from app.services.stock_screener import stock_screener_service
                screener_data = stock_screener_service.screen_stocks()
                top_sniper_picks = screener_data.get("top_sniper_picks", [])[:4]
                sector_perf = screener_data.get("sector_performance", {})
            except Exception as e:
                logger.debug(f"Could not fetch top sniper picks for tracker summary: {e}")

            return {
                "base_capital_per_trade": self.base_capital,
                "leverage": self.leverage,
                "exposure_per_trade": self.exposure_per_trade,
                "total_setups_today": total_setups_today,
                "a_plus_count": total_a_plus,
                "a_count": total_a,
                "active_count": len(self.active_setups),
                "closed_count": len(today_closed),
                "wins": wins,
                "losses": losses,
                "breakevens": breakevens,
                "win_rate_pct": win_rate,
                "unrealized_mtm": unrealized_mtm,
                "realized_gross": realized_gross,
                "realized_charges": realized_charges,
                "realized_net": realized_net,
                "total_combined_pnl": total_combined_pnl,
                "total_margin_deployed": total_margin_deployed,
                "active_setups": list(self.active_setups),
                "closed_setups": today_closed,
                "all_closed_history_count": len(self.closed_setups),
                "top_sniper_picks": top_sniper_picks,
                "sector_performance": sector_perf,
            }


